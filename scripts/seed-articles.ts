function makeParts(business: ContentBusiness, subject: Subject, industry: Industry): Parts {
  // 元の順序を保ったまま部分集合を取る（箇条書きの流れを保つため）
  const subset = <T>(arr: readonly T[], n: number): T[] => {
    const keep = new Set(
      pickN(
        arr.map((_, i) => i),
        n,
      ),
    );
    return arr.filter((_, i) => keep.has(i));
  };
  const what = pick(subject.what);
  // 「当社は…」で始まる導入文が2つ続かないようにする
  const hookPool = hooks[business].filter((h) => !(what.includes("当社") && h.includes("当社")));
  return {
    business,
    subject,
    reader: readerByIndustry[industry],
    hook: pick(hookPool),
    what,
    scope: pick(scopes),
    bgHeading: pick(bgHeadings[subject.kind]),
    bgLead: pick(bgLeads),
    bgClose: pick(bgCloses),
    causes: subset(subject.causes, 4),
    judgeHeading: pick(judgeHeadings),
    judgeLead: pick(judgeLeads),
    judgeSub: pick(judgeSubs),
    signs: subset(subject.signs, 4),
    judgeClose: pick(judgeCloses[business]),
    optHeading: pick(optHeadings),
    optLead: pick(optLeads),
    options: subset(subject.options, subject.options.length),
    stepSub: pick(stepSubs),
    stepLead: pick(stepLeads),
    steps: subset(subject.steps, 5),
    costHeading: subject.cost ? pick(costHeadings) : pick(noCostHeadings),
    costHedge: pick(costHedges),
    cautionLead: pick(cautionLeads),
    cautions: subset(subject.cautions, 3),
    timingSub: pick(timingSubs),
    timing: pick(timingExtras[business]),
    stanceSub: pick(stanceSubs),
    stance: pick(stanceExtras[business]),
    summaryHeading: pick(summaryHeadings),
    summaryLead: pick(summaryLeads),
    keyPoints: subset(subject.keyPoints, int(3, 4)),
    ending: pick(endings[business]),
  };
}

/**
 * level 0 = もっとも長い（補足段落2つ）… level 4 = もっとも短い。
 * 長さ調整は level を上下させるだけなので決定論的。
 */
function assemble(p: Parts, level: number): string {
  const s = p.subject;
  const f = s.focus;
  const n = {
    causes: [4, 4, 3, 3, 3][level],
    signs: [4, 4, 4, 3, 3][level],
    options: [4, 3, 3, 3, 2][level],
    steps: [5, 5, 4, 4, 4][level],
    cautions: [3, 3, 3, 2, 2][level],
    extras: [2, 1, 0, 0, 0][level],
    closes: level <= 2,
  };
  const L: string[] = [];
  const push = (...lines: string[]) => L.push(...lines, "");

  push(`${p.hook}${p.what}`);
  push(p.scope(f, p.reader));

  push(`## ${p.bgHeading(f)}`);
  push(p.bgLead);
  push(...p.causes.slice(0, n.causes).map((c) => `- ${c}`));
  if (n.closes) push(p.bgClose);

  push(`## ${p.judgeHeading}`);
  push(p.judgeLead);
  push(`### ${p.judgeSub}`);
  push(...p.signs.slice(0, n.signs).map((c) => `- ${c}`));
  if (n.closes) push(p.judgeClose);

  push(`## ${p.optHeading}`);
  push(p.optLead);
  push(
    "| 選択肢 | 特徴 |",
    "|---|---|",
    ...p.options.slice(0, n.options).map((o) => `| ${o.name} | ${o.desc} |`),
  );
  push(`### ${p.stepSub}`);
  push(p.stepLead);
  push(...p.steps.slice(0, n.steps).map((c, i) => `${i + 1}. ${c}`));

  push(`## ${p.costHeading}`);
  if (s.cost) push(`${s.cost}${p.costHedge}`);
  push(p.cautionLead);
  push(...p.cautions.slice(0, n.cautions).map((c) => `- ${c}`));
  if (n.extras >= 1) {
    push(`### ${p.timingSub}`);
    push(p.timing);
  }
  if (n.extras >= 2) {
    push(`### ${p.stanceSub}`);
    push(p.stance);
  }

  push(`## ${p.summaryHeading}`);
  push(p.summaryLead);
  push(...p.keyPoints.map((c) => `- ${c}`));
  push(`${s.next}${p.ending}`);
  L.push(DISCLAIMER);
  return L.join("\n") + "\n";
}

/** 本文の文字数（見出し記号・箇条書き記号・表の罫線・空白を除く） */
function bodyLength(body: string): number {
  return body
    .split("\n")
    .filter((l) => !/^\|---/.test(l))
    .map((l) =>
      l
        .replace(/^#{2,3}\s+/, "")
        .replace(/^(-|\d+\.)\s+/, "")
        .replace(/\|/g, ""),
    )
    .join("")
    .replace(/\s/g, "").length;
}

const MIN_CHARS = 800;
const MAX_CHARS = 1500;

function buildBody(p: Parts): string {
  let level = int(0, 2);
  let body = assemble(p, level);
  for (let i = 0; i < 6; i++) {
    const len = bodyLength(body);
    if (len > MAX_CHARS && level < 4) level++;
    else if (len < MIN_CHARS && level > 0) level--;
    else break;
    body = assemble(p, level);
  }
  return body;
}

// ───────────────────────── frontmatter まわり ─────────────────────────
function buildDescription(s: Subject, reader: string): string {
  const core = `${s.focus}について、${s.kind === "problem" ? "原因と判断のポイント" : "基本の考え方と判断のポイント"}、選択肢、${s.cost ? "費用の目安" : "注意点"}を${reader}向けに整理しました。`;
  const tails = shuffle([
    "はじめての方にも分かるよう、専門用語は最小限にしています。",
    "現場でよくある失敗例と、次に取るべき一歩もあわせて紹介します。",
    "当社の建設・飲食の現場経験をもとに、実務目線でまとめています。",
    "何から確認し、どう進めればよいかを順番に解説します。",
    "",
  ]);
  const nonEmpty = tails.filter((t) => t !== "");
  const combos = [
    ...tails.map((t) => core + t),
    ...nonEmpty.flatMap((a, i) => nonEmpty.slice(i + 1).map((b) => core + a + b)),
  ];
  const candidates = combos.filter((d) => d.length >= 80 && d.length <= 120);
  if (candidates.length > 0) return candidates[0];
  const d = combos[combos.length - 1];
  return d.length > 120 ? `${d.slice(0, 118).replace(/[、。]$/, "")}。` : d;
}

const titlePrefixes = ["【基礎知識】", "【保存版】", "【はじめての方へ】"];
function titleVariants(base: string, industry: Industry, year: number): string[] {
  return [
    base,
    `${base}｜${readerShortByIndustry[industry]}向け`,
    `${pick(titlePrefixes)}${base}`,
    `【${year}年版】${base}`,
    `${base}（${readerShortByIndustry[industry]}の場合）`,
  ];
}

const START = Date.UTC(2024, 9, 21); // 2024-10-21
const END = Date.UTC(2026, 9, 20); // 2026-10-20
const DAY = 86400000;
const TOTAL_DAYS = Math.round((END - START) / DAY);
const fmtDate = (ms: number) => new Date(ms).toISOString().slice(0, 10);

function pickPublishedAt(): number {
  let ms = START + int(0, TOTAL_DAYS) * DAY;
  // 週末はやや少なめにする（平日寄りの偏り）
  const dow = new Date(ms).getUTCDay();
  if ((dow === 0 || dow === 6) && chance(0.6)) ms = START + int(0, TOTAL_DAYS) * DAY;
  return ms;
}

const yamlStr = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const yamlArr = (a: readonly string[]) => `[${a.map(yamlStr).join(", ")}]`;

function toFrontmatter(fm: BlogFrontmatter): string {
  const lines = [
    `title: ${yamlStr(fm.title)}`,
    `slug: ${yamlStr(fm.slug)}`,
    `description: ${yamlStr(fm.description)}`,
    `publishedAt: ${yamlStr(fm.publishedAt)}`,
    `updatedAt: ${yamlStr(fm.updatedAt)}`,
    `business: ${yamlStr(fm.business)}`,
    `category: ${yamlStr(fm.category)}`,
    `tags: ${yamlArr(fm.tags)}`,
    `industry: ${yamlStr(fm.industry)}`,
    `challenge: ${yamlStr(fm.challenge)}`,
    `level: ${yamlStr(fm.level)}`,
  ];
  if (fm.budget) lines.push(`budget: ${yamlStr(fm.budget)}`);
  if (fm.region) lines.push(`region: ${yamlStr(fm.region)}`);
  lines.push(`author: ${yamlStr(fm.author)}`);
  if (fm.supervisor) lines.push(`supervisor: ${yamlStr(fm.supervisor)}`);
  lines.push(`heroImage: ${yamlStr(fm.heroImage)}`);
  lines.push(`relatedTools: ${yamlArr(fm.relatedTools)}`);
  lines.push(`keyPoints: ${yamlArr(fm.keyPoints)}`);
  lines.push(`isDummy: ${fm.isDummy ? "true" : "false"}`);
  return `---\n${lines.join("\n")}\n---\n`;
}

// ───────────────────────── メイン ─────────────────────────
function businessPlan(count: number): ContentBusiness[] {
  const build = Math.round(count * 0.5);
  const dining = Math.round(count * 0.35);
  const cross = count - build - dining;
  return shuffle<ContentBusiness>([
    ...Array<ContentBusiness>(build).fill("build"),
    ...Array<ContentBusiness>(dining).fill("dining"),
    ...Array<ContentBusiness>(cross).fill("cross"),
  ]);
}

/** 事業ごとに主題を均等に巡回させるキュー */
function subjectQueue(business: ContentBusiness) {
  const pool = THEMES.filter((t) => t.business === business).flatMap((t) =>
    t.subjects.map((s) => ({ theme: t, subject: s })),
  );
  let queue: typeof pool = [];
  return () => {
    if (queue.length === 0) queue = shuffle(pool);
    return queue.pop()!;
  };
}

function pickLevel(): Level {
  const r = rand();
  return r < 0.45 ? "beginner" : r < 0.85 ? "intermediate" : "advanced";
}

function pickAuthor(business: ContentBusiness): string {
  if (business === "build") return chance(0.75) ? "author-construction" : "author-site";
  if (business === "dining") return chance(0.75) ? "author-dining" : "author-site";
  const r = rand();
  return r < 0.4 ? "author-site" : r < 0.7 ? "author-construction" : "author-dining";
}

function pickSupervisor(business: ContentBusiness, subject: Subject): string | undefined {
  // 建設・横断（建設寄り）と、費用・補助金・衛生法令に関わる主題は監修必須
  const required = subject.supervisor || business !== "dining";
  if (!required && !chance(0.3)) return undefined;
  if (business === "build") return "sup-architect";
  if (business === "dining") return "sup-foodsafety";
  return chance(0.6) ? "sup-architect" : "sup-foodsafety";
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  if (CLEAN) {
    const removed = readdirSync(OUT_DIR).filter((f) => f.endsWith(".mdx"));
    for (const f of removed) unlinkSync(join(OUT_DIR, f));
    console.log(`Cleaned ${removed.length} files in content/blog/`);
  }

  const plan = businessPlan(COUNT);
  const queues: Record<ContentBusiness, () => { theme: Theme; subject: Subject }> = {
    build: subjectQueue("build"),
    dining: subjectQueue("dining"),
    cross: subjectQueue("cross"),
  };
  const usedSlugs = new Set<string>();
  const usedTitles = new Set<string>();
  const stats = {
    count: 0,
    chars: 0,
    min: Infinity,
    max: 0,
    byBusiness: { build: 0, dining: 0, cross: 0 } as Record<ContentBusiness, number>,
  };
  const byCategory = new Map<string, number>();
  let supervised = 0;

  for (const business of plan) {
    const { theme, subject } = queues[business]();
    const industry = pick(subject.industries);
    const challenge = pick(subject.challenges);
    const publishedMs = pickPublishedAt();
    const publishedAt = fmtDate(publishedMs);
    const updatedAt = chance(0.55) ? publishedAt : fmtDate(Math.min(END, publishedMs + int(7, 240) * DAY));
    const year = Number(publishedAt.slice(0, 4));

    // slug（日付＋主題キー。衝突時は連番）
    let slug = `${publishedAt}-${subject.key}`;
    for (let i = 2; usedSlugs.has(slug); i++) slug = `${publishedAt}-${subject.key}-${i}`;
    usedSlugs.add(slug);

    // タイトル（重複を避ける）
    const variants = shuffle(titleVariants(pick(subject.titles), industry, year));
    let title = variants.find((t) => !usedTitles.has(t));
    if (!title) {
      const base = variants[0];
      let i = 2;
      while (usedTitles.has(`${base}（${i}）`)) i++;
      title = `${base}（${i}）`;
    }
    usedTitles.add(title);

    const tags = [
      ...new Set([
        ...pickN(subject.tags, int(3, subject.tags.length)),
        ...(chance(0.5) ? [pick(businessTags[business])] : []),
      ]),
    ].slice(0, 8);
    const relatedTools: "reform"[] =
      (business === "build" && subject.reformTool && chance(0.8)) || (business === "cross" && chance(0.25))
        ? ["reform"]
        : [];

    const parts = makeParts(business, subject, industry);
    const body = buildBody(parts);

    const fm = blogFrontmatter.parse({
      title,
      slug,
      description: buildDescription(subject, readerByIndustry[industry]),
      publishedAt,
      updatedAt,
      business,
      category: theme.category,
      tags,
      industry,
      challenge,
      level: pickLevel(),
      budget: subject.budgets && chance(0.6) ? pick(subject.budgets) : undefined,
      region: chance(0.4) ? pick(regions) : undefined,
      author: pickAuthor(business),
      supervisor: pickSupervisor(business, subject),
      heroImage: pick(subject.heroImages),
      relatedTools,
      keyPoints: parts.keyPoints,
      isDummy: true,
    });

    if (!categories[business].includes(fm.category))
      throw new Error(`カテゴリー不整合: ${fm.category} (${business})`);
    const len = bodyLength(body);
    if (len < MIN_CHARS || len > MAX_CHARS)
      console.warn(`  ! ${slug}: 本文 ${len} 字（目安 ${MIN_CHARS}〜${MAX_CHARS}）`);

    writeFileSync(join(OUT_DIR, `${slug}.mdx`), toFrontmatter(fm) + "\n" + body, "utf8");

    stats.count++;
    stats.chars += len;
    stats.min = Math.min(stats.min, len);
    stats.max = Math.max(stats.max, len);
    stats.byBusiness[business]++;
    byCategory.set(fm.category, (byCategory.get(fm.category) ?? 0) + 1);
    if (fm.supervisor) supervised++;
  }

  console.log(`\nGenerated ${stats.count} articles → ${OUT_DIR}`);
  console.log(
    `  business : build ${stats.byBusiness.build} / dining ${stats.byBusiness.dining} / cross ${stats.byBusiness.cross}`,
  );
  console.log(`  category : ${[...byCategory.entries()].map(([k, v]) => `${k} ${v}`).join(" / ")}`);
  console.log(
    `  chars    : avg ${Math.round(stats.chars / stats.count)} (min ${stats.min} / max ${stats.max})`,
  );
  console.log(`  supervised: ${supervised} / ${stats.count}`);
  console.log(`  seed=${SEED} count=${COUNT}${CLEAN ? " --clean" : ""}`);
}

main();
